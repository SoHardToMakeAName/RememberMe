#!/usr/bin/env bash
# tests/v3-10round-test.sh
# 10 轮长对话：覆盖各种情绪 + 话题 + 知识密度梯度

cd "$(dirname "$0")/../.."

(
  # 1. 闲聊开场
  printf "今天下班路上看到夕阳特别好看，红得像烤熟的地瓜\n"
  sleep 35

  # 2. 渐进到情绪话题
  printf "但回来看到邮箱里有封 leader 发的邮件，问我周一要的那个东西交了没……我一看日历，今天周四\n"
  sleep 35

  # 3. 自嘲 + 轻吐槽
  printf "我同事说我做的是典型的'周一焦虑扩散到全周'，也不知道是不是\n"
  sleep 35

  # 4. 引导向深度
  printf "说实话我不是不喜欢这份工作，我是不喜欢自己一遇到事就崩的状态\n"
  sleep 35

  # 5. 知识密度测试（要回应有干货）
  printf "我之前看过一个说法叫'情绪粒度'，说能精确命名情绪的人抗压能力更强。这是真的吗\n"
  sleep 35

  # 6. 自我披露 + 调侃
  printf "但我感觉我现在词汇量不够，'难过''开心''烦躁'这三种就够我用了哈哈\n"
  sleep 35

  # 7. 切换轻松话题
  printf "话说你最近看了什么有意思的书吗？我想找点东西读\n"
  sleep 35

  # 8. 深度倾诉
  printf "其实我最近跟女朋友也有点问题……她觉得我太内耗，她太累\n"
  sleep 35

  # 9. 求助
  printf "我不知道该怎么办。我感觉我每次都把情绪甩给她，她接不住\n"
  sleep 35

  # 10. 收尾
  printf "谢谢你听我说这些\n"
  sleep 30

  printf "/quit\n"
) | bun run start 2>&1 | tee tests/v3-10round-test.log